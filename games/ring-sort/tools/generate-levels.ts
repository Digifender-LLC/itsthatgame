// Offline level generator for Ring Sort (dev tool, not shipped in the game bundle).
//
//   node tools/build-and-run.mjs            # bundles this file with esbuild and runs it
//   node tools/build-and-run.mjs 21 30      # only levels 21..30 (prints, does not write)
//
// For every level spec it tries seeded shuffles until one is solvable by the solver in
// src/logic.ts and its solution length (par) falls in the spec's band, then writes the
// committed data file src/level-data.ts. Runtime never generates anything.
import { writeFileSync } from "node:fs";
import { mulberry32 } from "../src/rng";
import { isComplete, newState, replay, solveDetailed, type RingLevel } from "../src/logic";
import { SPECS, type Spec } from "./specs";

interface Built {
  level: RingLevel;
  seed: number;
}

function build(spec: Spec, seed: number): Built {
  const rnd = mulberry32(seed);
  const n = spec.filled.length;
  const palette = [0, 1, 2, 3, 4, 5, 6];
  for (let i = palette.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [palette[i], palette[j]] = [palette[j]!, palette[i]!];
  }
  const colors = palette.slice(0, n);
  const rings: number[] = [];
  for (let c = 0; c < n; c++) for (let k = 0; k < spec.filled[c]!; k++) rings.push(colors[c]!);
  for (let i = rings.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [rings[i], rings[j]] = [rings[j]!, rings[i]!];
  }
  const pegs: number[][] = [];
  let at = 0;
  for (let p = 0; p < n; p++) {
    pegs.push(rings.slice(at, at + spec.filled[p]!));
    at += spec.filled[p]!;
  }
  for (let e = 0; e < spec.empties.length; e++) pegs.push([]);
  const caps = [...spec.filled, ...spec.empties];
  const hidden = caps.map(() => 0);
  if (spec.hide) {
    const order = pegs.map((_, i) => i).filter((i) => pegs[i]!.length > 0);
    for (let i = order.length - 1; i > 0; i--) {
      const j = Math.floor(rnd() * (i + 1));
      [order[i], order[j]] = [order[j]!, order[i]!];
    }
    const [count, depth] = spec.hide;
    for (const p of order.slice(0, count)) hidden[p] = Math.min(depth, pegs[p]!.length - 1);
  }
  const locks = caps.map(() => -1);
  if (spec.lock) for (const l of spec.lock) locks[l.peg] = colors[l.color]!;
  const level: RingLevel = { pegs, caps, hidden, locks };
  return { level, seed };
}

const only = process.argv.slice(2).map(Number);
const lo = only[0] ?? 1;
const hi = only[1] ?? SPECS.length;
const out: string[] = [];
let totalMs = 0;

SPECS.forEach((spec, idx) => {
  const num = idx + 1;
  if (num < lo || num > hi) return;
  const t0 = Date.now();
  let found: { b: Built; par: number; proven: boolean; sol: string } | null = null;
  let best: { b: Built; par: number; proven: boolean; sol: string; miss: number } | null = null;
  for (let attempt = 0; attempt < 1500 && !found; attempt++) {
    const b = build(spec, num * 10007 + attempt);
    const s = newState(b.level);
    if (s.pegs.some((_, p) => isComplete(s, p))) continue;
    let r = solveDetailed(s, { weight: 1, maxNodes: spec.exactNodes ?? 150_000 });
    if (!r) r = solveDetailed(s, { weight: 1.6, maxNodes: 200_000 });
    if (!r) continue;
    const par = r.moves.length;
    const sol = r.moves.map((m) => `${m.from}>${m.to}`).join(" ");
    const miss = par < spec.par[0] ? spec.par[0] - par : par > spec.par[1] ? par - spec.par[1] : 0;
    const cand = { b, par, proven: r.optimal, sol, miss };
    if (!best || miss < best.miss) best = cand;
    if (miss === 0) found = cand;
  }
  const pick = found ?? best;
  if (!pick) throw new Error(`level ${num}: no solvable seed`);
  if (
    !replay(
      pick.b.level,
      pick.sol.split(" ").map((t) => ({ from: +t.split(">")[0]!, to: +t.split(">")[1]! })),
    )
  ) {
    throw new Error(`level ${num}: solution does not replay`);
  }
  const ms = Date.now() - t0;
  totalMs += ms;
  const L = pick.b.level;
  console.log(
    `L${num} ${spec.filled.length}c ${L.pegs.length}p par=${pick.par}${pick.proven ? "" : "*"} ` +
      `seed=${pick.b.seed} band=${spec.par.join("-")}${found ? "" : " MISS"} ${ms}ms`,
  );
  const str = (v: unknown) => JSON.stringify(v);
  out.push(
    `  {\n    pegs: ${str(L.pegs.map((p) => p.join("")))},\n    caps: ${str(L.caps)},\n` +
      `    hidden: ${str(L.hidden)},\n    locks: ${str(L.locks)},\n    par: ${pick.par},\n` +
      `    proven: ${pick.proven},\n    seed: ${pick.b.seed},\n    solution: ${str(pick.sol)},\n  },`,
  );
});
console.log(`total ${totalMs}ms`);

if (!only.length) {
  const body =
    `// GENERATED by tools/generate-levels.ts: do not edit by hand.\n` +
    `// Each level was verified solvable by the solver in logic.ts; \`solution\` is a replayable\n` +
    `// move list ("from>to ..."), \`par\` its length. \`proven\` is true when the search finished\n` +
    `// with an admissible heuristic, so par is the true minimum; false means par is the best\n` +
    `// solution found within the search budget.\n` +
    `export interface LevelRecord {\n  pegs: string[];\n  caps: number[];\n  hidden: number[];\n` +
    `  locks: number[];\n  par: number;\n  proven: boolean;\n  seed: number;\n  solution: string;\n}\n\n` +
    `export const LEVEL_DATA: readonly LevelRecord[] = [\n${out.join("\n")}\n];\n`;
  writeFileSync(new URL("../src/level-data.ts", import.meta.url), body);
  console.log("wrote src/level-data.ts");
}
